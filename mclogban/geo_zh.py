_CHINA_NAMES = frozenset(
    {"中国", "China", "CHINA", "china", "中华人民共和国", "中国大陆", "CN"}
)


def zh_country(country: str, code: str = "") -> str:
    """国家名转中文。

    表里没有的原样返回；空值优先用国家代码兜底，再不行给「未知」。
    """
    raw = (country or "").strip()
    if raw in ("", "0", "-"):
        if code:
            key = (code or "").strip().upper()
            return COUNTRY_ZH.get(key, key)
        return "未知"
    if raw in _CHINA_NAMES:
        return "中国"
    return COUNTRY_ZH.get(raw, raw)


def zh_isp(isp: str) -> str:
    """运营商转中文；未收录的原样返回。"""
    raw = (isp or "").strip()
    if raw in ("", "0", "-"):
        return ""
    return ISP_ZH.get(raw, raw)


